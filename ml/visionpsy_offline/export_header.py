"""Convert the trained VisionPsy classifier to C++ constants for the Android build."""
import math
import struct
import sys
from pathlib import Path

LABELS = (
    'visible crack or opening',
    'possible damage to electrical contacts',
    'visible surface corrosion',
    'visible liquid or streaks',
)


def literal(value):
    if not math.isfinite(value):
        raise ValueError('Non-finite classifier parameter')
    return f'{value:.8e}f'


def main():
    input_path, output_path = map(Path, sys.argv[1:])
    payload = input_path.read_bytes()
    magic, dim, count = struct.unpack_from('<4sII', payload)
    if magic != b'VPH1' or dim != 960 or count != len(LABELS):
        raise ValueError('Unexpected VisionPsy classifier format')
    parameters = struct.unpack('<' + 'f' * (count * (dim * 2 + 2)), payload[12:])
    lines = [
        '// Generated by ml/visionpsy_offline/export_header.py.',
        '#pragma once',
        '#include <cstddef>',
        'namespace visionpsy_findings {',
        f'inline constexpr std::size_t embedding_size = {dim};',
        'struct Label { const char * text; float bias; float threshold_logit; float weights[embedding_size * 2]; };',
        'inline constexpr Label labels[] = {',
    ]
    for i, label in enumerate(LABELS):
        start = i * (dim * 2 + 2)
        *weights, bias, threshold = parameters[start:start + dim * 2 + 2]
        if not 0 < threshold < 1:
            raise ValueError(f'Invalid threshold for {label}')
        lines.append(f'    {{"{label}", {literal(bias)}, {literal(math.log(threshold / (1 - threshold)))}, {{')
        for offset in range(0, len(weights), 8):
            lines.append('        ' + ', '.join(map(literal, weights[offset:offset+8])) + ',')
        lines.append('    }},')
    lines.extend(('};', '}', ''))
    output_path.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
